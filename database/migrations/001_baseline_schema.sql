    updated_at     TIMESTAMP(6)     NULL DEFAULT NULL,
    PRIMARY KEY (assessment_id),
    CONSTRAINT fk_assessments_cs FOREIGN KEY (cs_id)
        REFERENCES class_sections (cs_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);


