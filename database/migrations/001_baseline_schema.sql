CREATE FUNCTION system_settings_protect_internal() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND OLD.is_internal = 1 THEN
        RAISE EXCEPTION 'Internal system_settings rows cannot be deleted';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.is_internal = 1
       AND (NEW.setting_key <> OLD.setting_key OR NEW.is_internal <> 1) THEN
        RAISE EXCEPTION 'Internal system_settings identity is immutable';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE TRIGGER trg_system_settings_internal_no_delete BEFORE DELETE ON system_settings
FOR EACH ROW EXECUTE FUNCTION system_settings_protect_internal();

CREATE TRIGGER trg_system_settings_internal_identity_guard BEFORE UPDATE ON system_settings
FOR EACH ROW EXECUTE FUNCTION system_settings_protect_internal();

CREATE FUNCTION touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP(6);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_user_accounts_updated_at BEFORE UPDATE ON user_accounts
FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
