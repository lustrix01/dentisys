-- Link historical rows to their owning session whenever the relationship is
-- unambiguous. Legacy date/code columns remain immutable snapshots for rows
-- that predate persistent sessions or have no session match.
UPDATE attendance_records r
   SET attendance_session_id = s.session_id
  FROM enrollments e,
       attendance_sessions s
 WHERE r.enrollment_id = e.enrollment_id
   AND s.cs_id = e.cs_id
   AND s.session_date = r.session_date
   AND s.session_code = r.session_code
   AND r.attendance_session_id IS NULL;

CREATE OR REPLACE FUNCTION validate_attendance_session_reference()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    session_row RECORD;
BEGIN
    IF NEW.attendance_session_id IS NULL THEN
        RETURN NEW;
    END IF;
    SELECT s.session_date, s.session_code, s.cs_id, e.cs_id AS enrollment_cs_id
      INTO session_row
      FROM attendance_sessions s
      JOIN enrollments e ON e.enrollment_id = NEW.enrollment_id
     WHERE s.session_id = NEW.attendance_session_id;
    IF NOT FOUND THEN
        -- Leave absent-session validation to the declarative foreign key so
        -- callers retain the existing 23503 error contract.
        RETURN NEW;
    END IF;
    IF NEW.session_date IS DISTINCT FROM session_row.session_date
       OR NEW.session_code IS DISTINCT FROM session_row.session_code THEN
        RAISE EXCEPTION 'attendance record snapshot does not match its attendance session';
    END IF;
    IF session_row.cs_id IS DISTINCT FROM session_row.enrollment_cs_id THEN
        RAISE EXCEPTION 'attendance record enrollment does not belong to its attendance session class';
    END IF;
    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_validate_attendance_session_reference ON attendance_records;
CREATE TRIGGER trg_validate_attendance_session_reference
