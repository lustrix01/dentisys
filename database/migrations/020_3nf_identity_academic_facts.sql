-- Additive 3NF support for canonical identity and repeated academic facts.
-- Legacy JSON and session snapshot columns remain during the compatibility
-- period. They are compatibility caches; the normalized relations below are
-- the controlled relational representation of the current facts.

CREATE TABLE IF NOT EXISTS person_identities (
    person_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_prefix         VARCHAR(50) NULL,
    first_name          VARCHAR(100) NULL,
    middle_name         VARCHAR(100) NULL,
    last_name           VARCHAR(100) NULL,
    name_suffix         VARCHAR(50) NULL,
    legacy_display_name VARCHAR(255) NULL,
    created_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

ALTER TABLE user_accounts
    ADD COLUMN IF NOT EXISTS person_id BIGINT NULL;

ALTER TABLE students
    ADD COLUMN IF NOT EXISTS person_id BIGINT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_user_accounts_person'
          AND conrelid = 'user_accounts'::regclass
    ) THEN
        ALTER TABLE user_accounts
            ADD CONSTRAINT fk_user_accounts_person
            FOREIGN KEY (person_id) REFERENCES person_identities(person_id)
            ON UPDATE RESTRICT ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_students_person'
          AND conrelid = 'students'::regclass
    ) THEN
        ALTER TABLE students
            ADD CONSTRAINT fk_students_person
            FOREIGN KEY (person_id) REFERENCES person_identities(person_id)
            ON UPDATE RESTRICT ON DELETE RESTRICT;
    END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_accounts_person
    ON user_accounts (person_id)
    WHERE person_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_students_person
    ON students (person_id)
    WHERE person_id IS NOT NULL;

-- Populate one canonical identity per account, then attach linked Students to
-- the same identity. Legacy display names are retained without guessing a
-- first/last split.
DO $$
DECLARE
    account_row RECORD;
    student_row RECORD;
    linked_person BIGINT;
BEGIN
    FOR account_row IN
        SELECT user_id, display_name, name_prefix, first_name, middle_name, last_name, name_suffix
        FROM user_accounts
        WHERE person_id IS NULL
    LOOP
        INSERT INTO person_identities (
            name_prefix, first_name, middle_name, last_name, name_suffix, legacy_display_name
        ) VALUES (
            account_row.name_prefix, account_row.first_name, account_row.middle_name,
            account_row.last_name, account_row.name_suffix, account_row.display_name
        ) RETURNING person_id INTO linked_person;

        UPDATE user_accounts
           SET person_id = linked_person
         WHERE user_id = account_row.user_id;
    END LOOP;

    FOR student_row IN
        SELECT student_id, user_id, student_account_user_id, name_prefix, first_name,
               middle_name, last_name, name_suffix
        FROM students
        WHERE person_id IS NULL
    LOOP
        linked_person := NULL;
        SELECT ua.person_id
          INTO linked_person
          FROM user_accounts ua
         WHERE ua.user_id = COALESCE(student_row.student_account_user_id, student_row.user_id)
           AND ua.person_id IS NOT NULL;

        IF linked_person IS NULL THEN
            INSERT INTO person_identities (
                name_prefix, first_name, middle_name, last_name, name_suffix
            ) VALUES (
                student_row.name_prefix, student_row.first_name, student_row.middle_name,
                student_row.last_name, student_row.name_suffix
            ) RETURNING person_id INTO linked_person;
        ELSE
            -- Student names are already structured and therefore may enrich an
            -- older ambiguous account display name without parsing it.
            UPDATE person_identities
               SET name_prefix = COALESCE(name_prefix, student_row.name_prefix),
                   first_name = COALESCE(first_name, student_row.first_name),
                   middle_name = COALESCE(middle_name, student_row.middle_name),
                   last_name = COALESCE(last_name, student_row.last_name),
                   name_suffix = COALESCE(name_suffix, student_row.name_suffix),
                   updated_at = CURRENT_TIMESTAMP(6)
             WHERE person_id = linked_person;
        END IF;

        UPDATE students
           SET person_id = linked_person
         WHERE student_id = student_row.student_id;
    END LOOP;
END
$$;

CREATE OR REPLACE FUNCTION sync_user_account_person_identity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.person_id IS NULL THEN
        INSERT INTO person_identities (
            name_prefix, first_name, middle_name, last_name, name_suffix, legacy_display_name
        ) VALUES (
            NEW.name_prefix, NEW.first_name, NEW.middle_name, NEW.last_name,
            NEW.name_suffix, NEW.display_name
        ) RETURNING person_id INTO NEW.person_id;
    ELSE
        UPDATE person_identities
           SET name_prefix = NEW.name_prefix,
               first_name = NEW.first_name,
               middle_name = NEW.middle_name,
               last_name = NEW.last_name,
               name_suffix = NEW.name_suffix,
               legacy_display_name = NEW.display_name,
               updated_at = CURRENT_TIMESTAMP(6)
         WHERE person_id = NEW.person_id;
    END IF;
    RETURN NEW;
END
$$;

