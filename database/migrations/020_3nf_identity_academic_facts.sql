-- A period membership's category determines its configuration. Keep the old
-- config_id/name/weight columns for existing API consumers, but maintain a
-- canonical relation whose determinant is category_id plus grading_period.
CREATE TABLE IF NOT EXISTS grading_category_period_memberships (
    category_period_id BIGINT PRIMARY KEY REFERENCES grading_category_periods(category_period_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES grading_categories(category_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    grading_period TEXT NOT NULL,
    name VARCHAR(255) NOT NULL,
    weight NUMERIC(7,4) NOT NULL,
    sort_order INTEGER NOT NULL,
    source_kind TEXT NOT NULL DEFAULT 'assessment',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT ck_gcpm_period CHECK (grading_period IN ('Midterm', 'Final')),
    CONSTRAINT ck_gcpm_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_gcpm_weight CHECK (weight > 0 AND weight <= 100),
    CONSTRAINT ck_gcpm_sort_order CHECK (sort_order > 0),
    CONSTRAINT ck_gcpm_source_kind CHECK (source_kind IN ('attendance', 'assessment')),
    CONSTRAINT uq_gcpm_category_period UNIQUE (category_id, grading_period)
);

INSERT INTO grading_category_period_memberships (
    category_period_id, category_id, grading_period, name, weight, sort_order, source_kind,
    created_at, updated_at
)
SELECT category_period_id, category_id, grading_period, name, weight, sort_order, source_kind,
       created_at, updated_at
  FROM grading_category_periods
ON CONFLICT (category_period_id) DO UPDATE SET
    category_id = EXCLUDED.category_id,
    grading_period = EXCLUDED.grading_period,
    name = EXCLUDED.name,
    weight = EXCLUDED.weight,
    sort_order = EXCLUDED.sort_order,
    source_kind = EXCLUDED.source_kind,
    updated_at = EXCLUDED.updated_at;

