CREATE OR REPLACE FUNCTION refresh_enrollment_remedial_state(
    target_enrollment_id INTEGER,
    remedial JSONB,
    target_updated_at TIMESTAMP(6)
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    exam_date_text TEXT;
BEGIN
    IF remedial IS NULL THEN
        DELETE FROM enrollment_remedial_states WHERE enrollment_id = target_enrollment_id;
        RETURN;
    END IF;

    exam_date_text := COALESCE(NULLIF(remedial->>'examDate', ''), NULLIF(remedial->>'dueDate', ''));
    INSERT INTO enrollment_remedial_states (
        enrollment_id, status, original_grade, remedial_score, remedial_grade,
        exam_date, notes, updated_at
    ) VALUES (
        target_enrollment_id,
        CASE WHEN remedial->>'status' IN ('pending', 'passed', 'failed', 'unavailable') THEN remedial->>'status' ELSE 'unavailable' END,
        normalization_jsonb_number(remedial->'originalGrade'),
        normalization_jsonb_number(remedial->'remedialScore'),
        normalization_jsonb_number(remedial->'remedialGrade'),
        CASE WHEN exam_date_text ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN exam_date_text::DATE ELSE NULL END,
        NULLIF(remedial->>'notes', ''),
        COALESCE(target_updated_at, CURRENT_TIMESTAMP(6))
    )
    ON CONFLICT (enrollment_id) DO UPDATE SET
        status = EXCLUDED.status,
        original_grade = EXCLUDED.original_grade,
        remedial_score = EXCLUDED.remedial_score,
        remedial_grade = EXCLUDED.remedial_grade,
        exam_date = EXCLUDED.exam_date,
        notes = EXCLUDED.notes,
        updated_at = EXCLUDED.updated_at;
END
$$;

