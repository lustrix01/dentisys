CREATE TABLE IF NOT EXISTS enrollment_grade_breakdowns (
    enrollment_id       INTEGER PRIMARY KEY REFERENCES enrollments(enrollment_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    calculation_mode    TEXT NULL,
    final_percentage    NUMERIC(5,2) NULL,
    final_gwa           NUMERIC(4,2) NULL,
    retention_state     TEXT NOT NULL,
    retention_threshold NUMERIC(4,2) NULL,
