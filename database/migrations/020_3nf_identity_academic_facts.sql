    CONSTRAINT ck_egb_percentage CHECK (final_percentage IS NULL OR (final_percentage >= 0 AND final_percentage <= 100)),
    CONSTRAINT ck_egb_gwa CHECK (final_gwa IS NULL OR (final_gwa >= 0 AND final_gwa <= 5)),
    CONSTRAINT ck_egb_retention CHECK (retention_state IN ('active', 'warning', 'critical', 'remedial', 'archived'))
);

CREATE TABLE IF NOT EXISTS enrollment_grade_breakdown_categories (
    enrollment_id   INTEGER NOT NULL REFERENCES enrollment_grade_breakdowns(enrollment_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    grading_period  TEXT NOT NULL,
    category_key    VARCHAR(255) NOT NULL,
    category_id     BIGINT NULL REFERENCES grading_categories(category_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    category_name   VARCHAR(255) NULL,
    earned_points   NUMERIC(12,4) NULL,
    possible_points NUMERIC(12,4) NULL,
    ratio           NUMERIC(12,8) NULL,
    weight          NUMERIC(7,4) NULL,
    contribution    NUMERIC(12,4) NULL,
    PRIMARY KEY (enrollment_id, grading_period, category_key),
    CONSTRAINT ck_egbc_period CHECK (grading_period IN ('overall', 'Midterm', 'Final'))
);

CREATE OR REPLACE FUNCTION normalization_jsonb_number(value JSONB)
RETURNS NUMERIC
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    raw_value TEXT;
BEGIN
    IF value IS NULL OR jsonb_typeof(value) NOT IN ('number', 'string') THEN
        RETURN NULL;
    END IF;
    raw_value := NULLIF(btrim(value #>> '{}'), '');
    IF raw_value IS NULL OR raw_value !~ '^-?[0-9]+(\\.[0-9]+)?$' THEN
        RETURN NULL;
    END IF;
    RETURN raw_value::NUMERIC;
END
$$;

CREATE OR REPLACE FUNCTION refresh_enrollment_grade_breakdown(
    target_enrollment_id INTEGER,
    components JSONB,
    target_percentage NUMERIC,
    target_gwa NUMERIC,
    target_retention_state TEXT,
    target_recorded_at TIMESTAMP(6)
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    category JSONB;
    category_index INTEGER;
    period_name TEXT;
    category_list JSONB;
    category_key_value TEXT;
BEGIN
    INSERT INTO enrollment_grade_breakdowns (
        enrollment_id, calculation_mode, final_percentage, final_gwa, retention_state,
        retention_threshold, recorded_at
    ) VALUES (
        target_enrollment_id,
        CASE WHEN components IS NULL THEN NULL ELSE components->>'calculationMode' END,
        target_percentage,
        target_gwa,
        target_retention_state,
        normalization_jsonb_number(CASE WHEN components IS NULL THEN NULL ELSE components->'retentionThreshold' END),
        COALESCE(target_recorded_at, CURRENT_TIMESTAMP(6))
    )
    ON CONFLICT (enrollment_id) DO UPDATE SET
        calculation_mode = EXCLUDED.calculation_mode,
        final_percentage = EXCLUDED.final_percentage,
        final_gwa = EXCLUDED.final_gwa,
        retention_state = EXCLUDED.retention_state,
        retention_threshold = EXCLUDED.retention_threshold,
        recorded_at = EXCLUDED.recorded_at;

    DELETE FROM enrollment_grade_breakdown_categories
     WHERE enrollment_id = target_enrollment_id;

    IF components IS NULL THEN
        RETURN;
    END IF;

    FOREACH period_name IN ARRAY ARRAY['overall', 'Midterm', 'Final'] LOOP
        category_list := CASE
            WHEN period_name = 'overall' THEN components->'categories'
            WHEN period_name = 'Midterm' THEN components->'periods'->'midterm'->'categories'
            ELSE components->'periods'->'final'->'categories'
        END;
        IF category_list IS NULL OR jsonb_typeof(category_list) <> 'array' THEN
            CONTINUE;
        END IF;

        category_index := 0;
        FOR category IN SELECT value FROM jsonb_array_elements(category_list) LOOP
            category_index := category_index + 1;
            category_key_value := COALESCE(
                NULLIF(category->>'categoryId', ''),
                NULLIF(category->>'name', ''),
                'category-' || category_index::TEXT
            );
            INSERT INTO enrollment_grade_breakdown_categories (
                enrollment_id, grading_period, category_key, category_id, category_name,
                earned_points, possible_points, ratio, weight, contribution
            ) VALUES (
                target_enrollment_id,
                period_name,
                category_key_value,
                CASE
                    WHEN category->>'categoryId' ~ '^[0-9]+$'
                     AND EXISTS (
                         SELECT 1 FROM grading_categories
                          WHERE category_id = (category->>'categoryId')::BIGINT
                     )
                    THEN (category->>'categoryId')::BIGINT
                    ELSE NULL
                END,
                NULLIF(category->>'name', ''),
                normalization_jsonb_number(category->'earnedPoints'),
                normalization_jsonb_number(category->'possiblePoints'),
                normalization_jsonb_number(category->'ratio'),
                normalization_jsonb_number(category->'weight'),
                normalization_jsonb_number(category->'contribution')
            )
            ON CONFLICT (enrollment_id, grading_period, category_key) DO UPDATE SET
                category_id = EXCLUDED.category_id,
                category_name = EXCLUDED.category_name,
                earned_points = EXCLUDED.earned_points,
                possible_points = EXCLUDED.possible_points,
                ratio = EXCLUDED.ratio,
                weight = EXCLUDED.weight,
                contribution = EXCLUDED.contribution;
        END LOOP;
    END LOOP;
END
$$;

CREATE OR REPLACE FUNCTION sync_enrollment_grade_breakdown()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM refresh_enrollment_grade_breakdown(
        NEW.enrollment_id, NEW.grade_components_json, NEW.final_percentage, NEW.final_gwa,
        NEW.retention_state, NEW.updated_at
    );
    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_enrollment_grade_breakdown ON enrollments;
CREATE TRIGGER trg_enrollment_grade_breakdown
AFTER INSERT OR UPDATE OF grade_components_json, final_percentage, final_gwa, retention_state
ON enrollments
FOR EACH ROW EXECUTE FUNCTION sync_enrollment_grade_breakdown();

INSERT INTO enrollment_grade_breakdowns (
    enrollment_id, calculation_mode, final_percentage, final_gwa, retention_state,
    retention_threshold, recorded_at
)
SELECT e.enrollment_id,
       e.grade_components_json->>'calculationMode',
       e.final_percentage,
       e.final_gwa,
       e.retention_state,
       normalization_jsonb_number(e.grade_components_json->'retentionThreshold'),
       COALESCE(e.updated_at, e.created_at, CURRENT_TIMESTAMP(6))
  FROM enrollments e
 WHERE e.grade_components_json IS NOT NULL
    OR e.final_percentage IS NOT NULL
    OR e.final_gwa IS NOT NULL
ON CONFLICT (enrollment_id) DO UPDATE SET
    calculation_mode = EXCLUDED.calculation_mode,
    final_percentage = EXCLUDED.final_percentage,
    final_gwa = EXCLUDED.final_gwa,
    retention_state = EXCLUDED.retention_state,
    retention_threshold = EXCLUDED.retention_threshold,
    recorded_at = EXCLUDED.recorded_at;

DO $$
DECLARE
    enrollment_row RECORD;
BEGIN
    FOR enrollment_row IN
        SELECT enrollment_id, grade_components_json, final_percentage, final_gwa,
               retention_state,
               COALESCE(updated_at, created_at, CURRENT_TIMESTAMP(6))::TIMESTAMP(6) AS recorded_at
        FROM enrollments
        WHERE grade_components_json IS NOT NULL
           OR final_percentage IS NOT NULL
           OR final_gwa IS NOT NULL
    LOOP
        PERFORM refresh_enrollment_grade_breakdown(
            enrollment_row.enrollment_id, enrollment_row.grade_components_json,
            enrollment_row.final_percentage, enrollment_row.final_gwa,
            enrollment_row.retention_state, enrollment_row.recorded_at
        );
    END LOOP;
END
$$;

